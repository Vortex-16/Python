# Box in a box pattern (like a photo frame, 8 in boxy type look)

def boxy_eight(n):
    if n < 3 or n % 2 == 0:
        print("Size should be an odd number and at least 3.")
        return
    for i in range(n):
        for j in range(n):
            # Print '*' for borders and the middle row (to look like '8')
            if (
                i == 0 or i == n-1 or           # Top and bottom borders
                i == n//2 or                   # Middle row
                j == 0 or j == n-1 or          # Left and right borders
                (i < n//2 and i != 0 and j == n-1) or  # Top right vertical
                (i > n//2 and i != n-1 and j == 0)     # Bottom left vertical
            ):
                print('*', end=' ')
            else:
                print(' ', end=' ')
        print()

# Example usage
boxy_eight(8)
print()
boxy_eight(9)
